## ------------------------------------------------------------
## 2. Initial values (from inits_1_m1_2.odc / inits_2_m1_2.odc)
##    WinBUGS used 2 chains -> reproduced here as a list of 2
## ------------------------------------------------------------

jags_inits <- list(
  list(LSE = 0.9, slope = 0.05, intercept = 1.1),
  list(LSE = 0.8, slope = 0.07, intercept = 1.3)
)

## ------------------------------------------------------------
## 3. Parameters to monitor (from script_cow_m1_2-v4.odc "set(...)")
## ------------------------------------------------------------

params <- c("slope", "intercept", "a", "b", "s", "t", "p", "q",
            "SE", "tau",
            "lnrs_pred", "lnrs_rep", "pvalue",
            "pvalues", "pvaluet", "pvaluep", "pvalueq",
            "ayst", "cst", "smax", "smsyst", "rmsyst", "msyst", "umsyst",
            "deviance")

## ------------------------------------------------------------
## 4. Run JAGS
##    WinBUGS schedule: compile(2 chains) -> update(2000) burn-in
##    -> dic.set() -> update(20000) sampling
## ------------------------------------------------------------

n.chains <- 2
n.adapt  <- 2000      # adaptation phase (JAGS-specific, not in WinBUGS)
n.burnin <- 2000      # matches update(2000) before dic.set()
n.iter   <- 20000     # matches update(20000)
n.thin   <- 1

model_file <- "R/model_cow_m1_2-v4.jags"   # place in working directory

jm <- jags.model(
  file     = model_file,
  data     = jags_data,
  inits    = jags_inits,
  n.chains = n.chains,
  n.adapt  = n.adapt
)

## burn-in
update(jm, n.iter = n.burnin)

## enable DIC monitoring (equivalent to WinBUGS dic.set())
load.module("dic")

## sample, keeping deviance for DIC
samples <- coda.samples(
  model = jm,
  variable.names = params,
  n.iter = n.iter,
  thin   = n.thin
)

